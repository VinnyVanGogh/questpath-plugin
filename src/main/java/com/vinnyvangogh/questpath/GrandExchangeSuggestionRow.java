package com.vinnyvangogh.questpath;

import java.util.function.Supplier;
import lombok.extern.slf4j.Slf4j;
import net.runelite.api.Client;
import net.runelite.api.VarClientStr;
import net.runelite.api.gameval.InterfaceID;
import net.runelite.api.widgets.JavaScriptCallback;
import net.runelite.api.widgets.Widget;
import net.runelite.api.widgets.WidgetType;

/**
 * questpath's own row in the Grand Exchange's item-search chatbox -- the
 * dialog that opens when a buy or sell slot is clicked, the one that already
 * carries the game's own "Previous search" line. This draws a second line
 * underneath it, showing whatever {@link GrandExchangeShoppingList} says to
 * buy next, clickable the same way "Previous search" is.
 *
 * <p><b>This replaces the first attempt at this feature, which drove the
 * search box from a Swing button instead of drawing inside the game's own
 * interface.</b> That attempt (see {@link GrandExchangeSearchBridge}'s class
 * doc) called {@code client.runScript(ScriptID.GE_ITEM_SEARCH)} with no
 * arguments and threw {@code AssertionError} on every click, because {@code
 * GE_ITEM_SEARCH} takes three -- a fact only discovered from the client's own
 * assertion message, since nothing on this project's classpath calls that
 * script forward. This class does not repeat that guess: {@link #select}
 * never calls {@code GE_ITEM_SEARCH} directly. See its own doc for what it
 * does instead.
 *
 * <p><b>Where this attaches, and why not {@code InterfaceID.GeOffers}.</b>
 * The panel described in this project's brief -- "What would you like to
 * buy? / Previous search: (icon) Air diamond / ... / Show last searched" --
 * is not the buy/sell setup screen ({@code InterfaceID.GeOffers.UNIVERSE},
 * group 465). It is the generic item-search chatbox RuneScape reuses for
 * several different searches (the Grand Exchange included), packed group
 * 162, {@code InterfaceID.Chatbox}. Its root layer, {@link
 * InterfaceID.Chatbox#MES_LAYER} (10616871, packed), is exactly the widget
 * {@code com.questhelper.bank.banktab.QuestGrandExchangeInterface} hangs its
 * own quest-related icon from in the installed {@code quest-helper} jar --
 * confirmed with {@code javap -c -p} against {@code
 * ~/.runelite/plugins/quest-helper_*.jar}'s {@code
 * QuestGrandExchangeInterface.class} and {@code QuestBankTab.class}, not
 * assumed from the constant's name. That class's own {@code notAtGE()} check
 * and package (`bank.banktab`, alongside a real {@code QuestGrandExchangeInterface}
 * type) confirm Quest Helper does reach into the Grand Exchange's own search
 * flow through this widget, even though it never touches {@code GeOffers} --
 * the two facts are not in tension once the panel in the brief is recognised
 * as this chatbox rather than the offer screen itself.
 *
 * <p><b>The widget shape is copied from this project's own {@link
 * BankButton}</b>, which is itself the same shape {@code
 * com.questhelper.bank.banktab.QuestBankTabInterface} uses (disassembled
 * independently, same jar): {@code parent.createChild(-1,
 * WidgetType.GRAPHIC)}, {@code setOriginalWidth}/{@code setOriginalHeight}/
 * {@code setOriginalX}/{@code setOriginalY}, {@code setSpriteId} or {@code
 * setItemId}, {@code setOnOpListener} with a {@link JavaScriptCallback},
 * {@code setHasListener(true)}, {@code setAction}, {@code revalidate()}. The
 * text line's shape -- {@code createChild(-1, WidgetType.TEXT)}, {@code
 * setTextShadowed}, {@code setXTextAlignment}/{@code setYTextAlignment},
 * {@code setText}, {@code setFontId}, {@code setTextColor}, {@code
 * revalidate()} -- is copied the same way from {@code
 * QuestGrandExchangeInterface#createTitleStepNeededItem}, which also
 * confirms {@code setText} accepts {@code <col=RRGGBB>...</col>} markup
 * inside this exact interface (it ships {@code "<col=b40000>Quest
 * Helper</col> Items"} literally), which is how {@link #label} colours its
 * own "Quest Path:" prefix without a second text widget.
 *
 * <p><b>Never drawn on top of whatever else is already in the box</b> -- the
 * player's own instruction, after the bank tab button collided with Quest
 * Helper's at a shared fixed coordinate once already (see {@link BankButton}'s
 * {@code BUTTON_X} doc). The native "Previous search" row's position is
 * generated by the client's own script and is not a published constant, so
 * rather than guess a coordinate that might land on it, {@link #belowExisting}
 * reads every dynamic child {@link InterfaceID.Chatbox#MES_LAYER} already has
 * at attach time and places this row's own top edge below all of them. That
 * is correct regardless of what the native layout actually is, which a fixed
 * offset copied from a screenshot could not promise.
 *
 * <p><b>Rebuilt on every attach, never trusted to survive one.</b> {@link
 * #attach} is called from {@code QuestpathPlugin} on two events: {@code
 * WidgetLoaded} for {@link InterfaceID#CHATBOX} (the box just opened) and
 * {@code ScriptPostFired} for {@code ScriptID.GE_ITEM_SEARCH} (752 -- the
 * script {@code GrandExchangePlugin.onScriptPostFired} itself reacts to for
 * this exact box, per {@link GrandExchangeSearchBridge}'s own verified class
 * doc, so a search just ran and the box's own content may have just been
 * rebuilt under this row). Each call checks whether this row's own widgets
 * are still among {@link InterfaceID.Chatbox#MES_LAYER}'s dynamic children
 * -- the same staleness check {@code
 * com.banktaglayouts.BankTagLayoutsPlugin#updateButton} uses in the installed
 * {@code bank-tag-layouts} jar -- and only recreates them when they are gone.
 *
 * <p><b>Every widget call here can throw, and the failure mode is not a
 * caught exception.</b> {@link #attach} and {@link #select} both wrap their
 * real work in {@code catch (RuntimeException | AssertionError)}, logged at
 * warn -- see {@link GrandExchangeSearchBridge}'s own class doc and {@code
 * ShortestPathBridge}'s for exactly why an {@code AssertionError} from the
 * client is an {@code Error}, not an {@code Exception}, and tears through an
 * ordinary catch. Both are only ever called from the client thread already:
 * {@link #attach} from {@code QuestpathPlugin}'s own event subscribers (which
 * RuneLite always runs there), {@link #select} from a {@link
 * JavaScriptCallback}, which the client's own script engine invokes from
 * nowhere else.
 *
 * <p><b>This is unverified in a running client.</b> Neither the author of
 * this class nor the player who requested it can launch one from this
 * environment. Every member used here was confirmed to exist, on this exact
 * dependency version, either by {@code javap} against the installed jars
 * named above or against this project's own compiled {@code
 * runelite-api-1.12.37.jar}. What is not confirmed is that the row actually
 * appears where intended, does not overlap anything, or that {@link #select}
 * visibly changes the search results -- see that method's own doc for
 * exactly how far its own claim goes.
 */
@Slf4j
class GrandExchangeSuggestionRow
{
	/** Square icon size, matching {@link BankButton}'s own {@code SIZE - ICON_INSET * 2} inner icon. */
	private static final int ICON_SIZE = 18;

	/** Gap between the icon and the text that follows it. */
	private static final int ICON_TEXT_GAP = 4;

	/** Left space kept clear of the chatbox's own scrollbar/edge when no sibling text gives a better margin. */
	private static final int DEFAULT_LEFT_MARGIN = 8;

	/** Right margin kept clear of the chatbox's own edge when sizing the text widget. */
	private static final int RIGHT_MARGIN = 8;

	/** Vertical gap between this row and whatever the box already has above it. */
	private static final int GAP_BELOW_EXISTING = 6;

	/**
	 * Falls back to this when {@link GrandExchangeShoppingList.Line#itemId()}
	 * is 0 -- questpath holds no item id for the name. The same sprite {@link
	 * BankButton} already uses and this project has already shipped, chosen
	 * over inventing a new one: a bag, standing in for "something to buy"
	 * when there is no real item icon to draw.
	 */
	private static final int SPRITE_FALLBACK_ICON = 777;

	/**
	 * questpath's own brand orange ({@code
	 * net.runelite.client.ui.ColorScheme.BRAND_ORANGE}, confirmed via {@code
	 * javap} against the installed {@code client-1.12.37.jar}'s static
	 * initialiser: {@code new Color(220, 138, 0)}), packed the way {@code
	 * Color.getRGB()} would return it and {@link Widget#setTextColor(int)}
	 * and the {@code <col=>} markup both expect: {@code 0xRRGGBB}.
	 */
	private static final int BRAND_ORANGE = 0xDC8A00;

	/** A font already confirmed to render in this exact interface -- {@code QuestGrandExchangeInterface} uses it for its own title line. */
	private static final int FONT_ID = 496;

	private final Client client;
	private final Supplier<GrandExchangeShoppingList.Line> suggestion;

	private Widget icon;
	private Widget text;
	private String selectedName;

	/**
	 * @param client this plugin's own client, never Quest Helper's or
	 *     anyone else's -- everything this class reaches is RuneLite's own
	 *     public API, no reflection involved
	 * @param suggestion the current head of the account's Grand Exchange
	 *     shopping list, or null when there is nothing to suggest. Read
	 *     fresh on every {@link #attach}, never cached here -- production
	 *     wiring is a reference to whatever {@code QuestpathPlugin} last
	 *     computed, which is already cheap to read because that computation
	 *     runs on its own schedule, not this row's
	 */
	GrandExchangeSuggestionRow(Client client, Supplier<GrandExchangeShoppingList.Line> suggestion)
	{
		this.client = client;
		this.suggestion = suggestion;
	}

	/**
	 * Draws or refreshes the row. Safe to call whenever the search chatbox
	 * might have just appeared or been rebuilt -- see class doc for the two
	 * events {@code QuestpathPlugin} calls this from, and why neither one is
	 * trusted alone. A no-op, not a failure, when the chatbox is not open or
	 * there is nothing to suggest right now -- see {@link #attachNow}.
	 */
	void attach()
	{
		try
		{
			attachNow();
		}
		catch (RuntimeException | AssertionError e)
		{
			// See class doc: AssertionError is deliberate, not a typo.
			log.warn("Could not draw questpath's Grand Exchange suggestion row", e);
		}
	}

	private void attachNow()
	{
		Widget parent = client.getWidget(InterfaceID.Chatbox.MES_LAYER);
		if (parent == null || parent.isHidden())
		{
			// Not the search chatbox right now. The client already discarded
			// whatever this row had -- nothing left here to hide.
			forget();
			return;
		}

		GrandExchangeShoppingList.Line line = suggestion.get();
		if (line == null)
		{
			// Nothing outstanding to buy. Hide rather than leave a stale
			// suggestion on screen -- an empty shopping list is not "buy
			// whatever this said last".
			hide();
			return;
		}

		if (!stillPresent(parent, icon) || !stillPresent(parent, text))
		{
			// The box rebuilt its children under us -- these references are
			// stale even though they have not thrown yet. Rebuild both
			// together rather than mixing a live one with a dead one.
			icon = null;
			text = null;
		}

		int x = leftMargin();
		int y = belowExisting(parent);

		if (icon == null)
		{
			icon = parent.createChild(-1, WidgetType.GRAPHIC);
			icon.setOriginalWidth(ICON_SIZE);
			icon.setOriginalHeight(ICON_SIZE);
			icon.setHasListener(true);
			icon.setOnOpListener((JavaScriptCallback) event -> select());
		}
		icon.setOriginalX(x);
		icon.setOriginalY(y);
		icon.setAction(0, "Search for " + line.name());
		if (line.itemId() > 0)
		{
			icon.setItemId(line.itemId());
		}
		else
		{
			icon.setSpriteId(SPRITE_FALLBACK_ICON);
		}
		icon.setHidden(false);
		icon.revalidate();

		if (text == null)
		{
			text = parent.createChild(-1, WidgetType.TEXT);
			text.setTextShadowed(true);
			text.setXTextAlignment(0);
			text.setYTextAlignment(1);
			text.setFontId(FONT_ID);
			text.setHasListener(true);
			text.setOnOpListener((JavaScriptCallback) event -> select());
		}
		text.setOriginalX(x + ICON_SIZE + ICON_TEXT_GAP);
		text.setOriginalY(y);
		text.setOriginalHeight(ICON_SIZE);
		text.setOriginalWidth(textWidth(parent, x));
		text.setText(label(line));
		text.setAction(0, "Search for " + line.name());
		text.setHidden(false);
		text.revalidate();

		selectedName = line.name();
	}

	/**
	 * Sets the search box's text to whatever this row last showed, then asks
	 * the box itself to react to it -- see class doc for why this exists at
	 * all instead of calling {@code ScriptID.GE_ITEM_SEARCH} directly.
	 *
	 * <p>{@code setVarcStrValue} alone was the half of the original,
	 * verified-safe call that never threw -- it is real client state, just
	 * not enough on its own to make the box re-filter, because {@code
	 * GrandExchangePlugin.onScriptPostFired} only reacts to script 752
	 * running, and this class does not know 752's own three arguments. What
	 * it does instead: {@code
	 * com.questhelper.bank.banktab.QuestGrandExchangeInterface} in the
	 * installed {@code quest-helper} jar hits the identical problem --
	 * forcing this same box to react to a change it made -- against this
	 * exact widget, {@link InterfaceID.Chatbox#MES_TEXT2} (10616876, the
	 * search input itself), by reading that widget's own {@code
	 * getOnKeyListener()} and handing the result straight back to {@code
	 * client.runScript}. That listener is the game's own, already correctly
	 * shaped for whatever script it calls -- nothing here invents an
	 * argument list. Confirmed by {@code javap -c -p} against {@code
	 * QuestGrandExchangeInterface.class}'s {@code updateSearchInterface}
	 * method; not confirmed against a running client, so whether replaying
	 * that listener actually re-filters the results the way clicking inside
	 * the box would is this method's one unverified claim -- see class doc.
	 *
	 * <p>{@code null} from either lookup is treated as "nothing to replay",
	 * not an error: the input widget not existing means the box changed
	 * shape between drawing this row and clicking it, which is the same
	 * "went stale" case {@link #attachNow} already handles on the next
	 * {@link #attach}.
	 */
	private void select()
	{
		String itemName = selectedName;
		if (itemName == null)
		{
			return;
		}
		try
		{
			client.setVarcStrValue(VarClientStr.INPUT_TEXT, itemName);
			Widget input = client.getWidget(InterfaceID.Chatbox.MES_TEXT2);
			if (input == null)
			{
				log.info("questpath's Grand Exchange row set \"{}\" but the search box itself was gone", itemName);
				return;
			}
			Object[] listener = input.getOnKeyListener();
			if (listener == null)
			{
				log.info("questpath's Grand Exchange row set \"{}\" but the search box has no listener to replay",
					itemName);
				return;
			}
			client.runScript(listener);
			log.info("questpath's Grand Exchange row selected \"{}\"", itemName);
		}
		catch (RuntimeException | AssertionError e)
		{
			log.warn("Selecting \"{}\" from questpath's Grand Exchange row failed", itemName, e);
		}
	}

	/**
	 * Hides the row and forgets its widgets -- called when the plugin itself
	 * is switched off, the way {@link BankButton#detach} is. Safe even when
	 * the chatbox has already closed on its own: {@code setHidden} on a
	 * widget the client already discarded is a no-op, not a throw.
	 */
	void detach()
	{
		hide();
		forget();
	}

	/** Hides both widgets without forgetting them -- the box is still open, just with nothing to suggest right now. */
	private void hide()
	{
		if (icon != null)
		{
			icon.setHidden(true);
		}
		if (text != null)
		{
			text.setHidden(true);
		}
	}

	/** Forgets both widgets outright -- the chatbox itself is gone, and the client already discarded them with it. */
	private void forget()
	{
		icon = null;
		text = null;
		selectedName = null;
	}

	/** Whether widget is still among parent's own current children -- see class doc's staleness paragraph. */
	private static boolean stillPresent(Widget parent, Widget widget)
	{
		if (widget == null)
		{
			return false;
		}
		Widget[] children = parent.getDynamicChildren();
		if (children == null)
		{
			return false;
		}
		for (Widget child : children)
		{
			if (child == widget)
			{
				return true;
			}
		}
		return false;
	}

	/**
	 * The Y coordinate below every dynamic child parent already has, this
	 * row's own two widgets excluded -- see class doc for why this is
	 * computed rather than a fixed offset.
	 */
	private int belowExisting(Widget parent)
	{
		int maxBottom = 0;
		Widget[] children = parent.getDynamicChildren();
		if (children != null)
		{
			for (Widget child : children)
			{
				if (child == icon || child == text)
				{
					continue;
				}
				int bottom = child.getOriginalY() + child.getOriginalHeight();
				if (bottom > maxBottom)
				{
					maxBottom = bottom;
				}
			}
		}
		return maxBottom + GAP_BELOW_EXISTING;
	}

	/**
	 * The left edge to line up with -- the prompt text's own left edge
	 * ({@link InterfaceID.Chatbox#MES_TEXT}, "What would you like to buy?")
	 * when it is present, {@link #DEFAULT_LEFT_MARGIN} otherwise.
	 */
	private int leftMargin()
	{
		Widget prompt = client.getWidget(InterfaceID.Chatbox.MES_TEXT);
		return prompt != null ? prompt.getOriginalX() : DEFAULT_LEFT_MARGIN;
	}

	/** How wide the text widget can be before running into the chatbox's own right edge. */
	private int textWidth(Widget parent, int x)
	{
		int parentWidth = parent.getWidth();
		if (parentWidth <= 0)
		{
			parentWidth = parent.getOriginalWidth();
		}
		int width = parentWidth - x - ICON_SIZE - ICON_TEXT_GAP - RIGHT_MARGIN;
		return Math.max(width, ICON_SIZE);
	}

	/**
	 * "Quest Path: " in {@link #BRAND_ORANGE}, followed by the item name and,
	 * when more than one is still needed, the outstanding count -- see class
	 * doc for where the {@code <col=>} markup itself was confirmed.
	 */
	private static String label(GrandExchangeShoppingList.Line line)
	{
		StringBuilder text = new StringBuilder("<col=")
			.append(String.format("%06x", BRAND_ORANGE))
			.append(">Quest Path:</col> ")
			.append(line.name());
		if (line.outstanding() > 1)
		{
			text.append(" (x").append(line.outstanding()).append(')');
		}
		return text.toString();
	}
}
