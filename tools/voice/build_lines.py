#!/usr/bin/env python3
"""Write the voice word list (lines.tsv) from the quest bundle the plugin ships.

Reads src/main/resources/com/vinnyvangogh/questpath/quests.json and writes
src/main/resources/com/vinnyvangogh/questpath/voice/lines.tsv: the fixed
phrases, the numbers, one row per item name a quest can ask for, a plural row
per item a shop sells, and one row per shop. VoiceLinesCoverageTest fails if
the bundle names an item or shop this list has no row for, so re-run this
whenever quests.json changes, then render the new clips with generate_voice.py.

Developer tool only: never shipped in the jar and never run by the plugin.

    python3 tools/voice/build_lines.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "src/main/resources/com/vinnyvangogh/questpath"
BUNDLE = RES / "quests.json"
OUT = RES / "voice/lines.tsv"

HEADER = """\
# Voice lines: the one word list for both the plugin (VoiceLines.java) and
# the clip generator (tools/voice/generate_voice.py). Generated by
# tools/voice/build_lines.py from quests.json; hand edits to the spoken column
# are fine (pronunciation), but re-running the builder overwrites them.
# Tab separated:
#   kind	key	clip	spoken
# kind phrase: a fixed word, key = its name in VoiceLines
# kind number: a count, key = the number
# kind item:   an item, key = the item name in lower case
# kind plural: the same item said for more than one, key = the item name in lower case
# kind shop:   a shop, key = the shop name in lower case; spoken carries its "the"
# Each clip is voice/<clip>.wav. Voice: Kokoro af_heart (see generate_voice.py).
"""

PHRASES = [
    ("looking-for", "Looking for"),
    ("and", "and"),
    ("at", "at"),
    ("nearby", "nearby"),
    ("a", "a"),
    ("an", "an"),
    ("hundred", "hundred"),
    ("thousand", "thousand"),
]

NUMBERS = range(1, 101)

# Words that keep their own form in the plural ("30 bones", "5 coins").
UNCOUNTED = {"bones", "ashes", "coins", "logs", "berries", "seeds", "leaves", "fur", "wool",
             "sand", "clay", "coal", "grain", "flour", "malt", "salt", "glass", "feathers",
             "runes", "bars", "ore", "fungus", "nails", "tokens", "planks", "eggs", "yeast",
             "bread", "salmon", "tuna", "cod", "mackerel", "swordfish", "beef", "meat", "silk",
             "charcoal", "garlic", "seaweed", "essence", "dust", "vodka", "rum", "spice"}

# Plurals no rule above gets right.
IRREGULAR = {"knife": "knives", "potato": "potatoes", "tomato": "tomatoes", "staff": "staves"}

# One-word shop names that are not a shopkeeper's own name: "the Armoury", "the Cook".
PLACE_WORDS = {"armoury", "barmaid", "bartender", "cook"}


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "x"


def spoken_item(name):
    """What to say for an item: the name without wiki parentheticals."""
    return re.sub(r"\s*\([^)]*\)", "", name).strip() or name


def plural(words):
    """English plural of an item phrase: the head noun, before any "of"."""
    head, sep, tail = words.partition(" of ")
    parts = head.split(" ")
    last = parts[-1]
    low = last.lower()
    if low in UNCOUNTED or low.endswith("s"):
        return words
    if low in IRREGULAR:
        last = last[0] + IRREGULAR[low][1:]
    elif re.search(r"[^aeiou]y$", low):
        last = last[:-1] + "ies"
    elif re.search(r"(x|z|ch|sh)$", low):
        last = last + "es"
    else:
        last = last + "s"
    parts[-1] = last
    return " ".join(parts) + (sep + tail if sep else "")


def spoken_shop(name):
    """What to say for a shop, with "the" where English wants one."""
    words = re.sub(r"\s*\([^)]*\)", "", name).strip().rstrip(".").strip()
    if "'" in words or "’" in words:
        return words  # "Aubury's Rune Shop", "Ali's Discount Wares"
    if re.search(r"\bthe\b", words, re.IGNORECASE):
        return words  # "Ali the Kebab seller" already has one
    if words.lower() in PLACE_WORDS:
        return "the " + words  # one word, but a place: "the Armoury"
    if len(words.split()) == 1:
        return words  # a shopkeeper's own name: "Alain", "Argo"
    return "the " + words  # "the Blue Moon Inn", "the Al Kharid General Store"


def bundle_names(bundle):
    """(every item name a line can carry, the names a shop sells, every shop)."""
    items, sold = set(), set()
    for quest in bundle["quests"]:
        for key in ("items", "recommended_items"):
            for item in quest.get(key) or []:
                sells = bool(item.get("shop_names"))
                if item.get("item_id", 0) > 0 or sells:
                    items.add(item["name"])
                    if sells:
                        sold.add(item["name"])
                for alt in item.get("alternatives") or []:
                    items.add(alt["name"])
                    if sells:
                        sold.add(alt["name"])
    shops = {shop["name"] for shop in bundle["shops"]}
    return items, sold, shops


def build_rows(items, sold, shops):
    """(rows, clip id -> words): every list row, and each clip once."""
    rows = []
    used = {}

    def clip_for(kind, key, words):
        base = f"{kind}-{slug(key)}" if kind != "phrase" else key
        clip = base
        n = 2
        while clip in used and used[clip] != words:
            clip = f"{base}-{n}"
            n += 1
        used[clip] = words
        return clip

    for key, words in PHRASES:
        rows.append(("phrase", key, clip_for("phrase", key, words), words))
    for n in NUMBERS:
        rows.append(("number", str(n), clip_for("num", str(n), str(n)), str(n)))
    for name in sorted(items, key=str.lower):
        words = spoken_item(name)
        rows.append(("item", name.lower(), clip_for("item", name, words), words))
    for name in sorted(sold, key=str.lower):
        words = plural(spoken_item(name))
        clip = clip_for("item", name, words) if words == spoken_item(name) else clip_for("items", name, words)
        rows.append(("plural", name.lower(), clip, words))
    for name in sorted(shops, key=str.lower):
        words = spoken_shop(name)
        rows.append(("shop", name.lower(), clip_for("shop", name, words), words))
    return rows, used


def main():
    bundle = json.loads(BUNDLE.read_text(encoding="utf-8"))
    items, sold, shops = bundle_names(bundle)
    rows, used = build_rows(items, sold, shops)
    for row in rows:
        if any("\t" in cell or "\n" in cell for cell in row):
            raise SystemExit(f"tab or newline in {row!r}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "".join("\t".join(r) + "\n" for r in rows), encoding="utf-8")
    chars = sum(len(w) for w in used.values())
    print(f"{len(rows)} rows, {len(used)} clips, {len(items)} items, {len(sold)} sold, {len(shops)} shops,"
          f" {chars} characters to say")
    return 0


if __name__ == "__main__":
    sys.exit(main())
